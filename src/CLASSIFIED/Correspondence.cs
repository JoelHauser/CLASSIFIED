            string[] surnames = bear ? BearSurnames : UsecSurnames;
            string name = initials[random.Next(initials.Length)] + ". " + surnames[random.Next(surnames.Length)];
            string title = sender ?? department.Titles[random.Next(department.Titles.Length)];
            string code = sender != null ? CodeFor(sender) : department.Code;
            return $"SIGNED: {name}, {title}  //  REF {code}-{random.Next(100, 10000):0000}";
        }

        private static string CodeFor(string sender)
        {
            switch (sender)
            {
                case "CHIEF OF STAFF":
                case "COMMAND POST": return "SHT";
                case "QUARTERMASTER":
                case "SUPPLY": return "TYL";
                case "SPECIAL DEPARTMENT": return "OSO";
                case "MEDICAL SERVICE":
                case "MEDICAL": return "MED";
                case "SIGNALS": return "SVZ";
                case "RECONNAISSANCE": return "RAZ";
                case "OPERATIONS": return "OPS";
                case "S2 INTELLIGENCE": return "S2";
                case "S4 LOGISTICS": return "S4";
                case "S6 COMMUNICATIONS": return "S6";
                case "CORPORATE COMMAND": return "HQ";
                default: return "GEN";
            }
        }

        private static List<string> Join(string[] a, string[] b)
        {
            var all = new List<string>();
            if (a != null)
            {
                all.AddRange(a);
            }
            if (b != null)
            {
                all.AddRange(b);
            }
            return all;
        }
